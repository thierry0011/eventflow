"""
Alembic environment.

MIGRATIONS ARE NOT OPTIONAL, and this is the part SQLAlchemy does not give you
for free the way Django does.

The rules that keep a production database safe:

1. EVERY schema change is a migration file, reviewed like code. No manual
   ALTER TABLE in psql, ever — because the next environment will not have it.

2. MIGRATIONS MUST BE BACKWARD COMPATIBLE during a rolling deploy. For a few
   minutes the old and new code both run against the same schema. So:
       adding a nullable column         safe
       adding a column with a default   safe in PG 11+ (no table rewrite)
       dropping a column                NOT SAFE in one step
       renaming a column                NOT SAFE in one step
   To remove or rename, use the EXPAND / CONTRACT pattern across releases:
       release 1  add the new column, write to BOTH
       release 2  backfill, switch reads to the new column
       release 3  stop writing the old one
       release 4  drop it
   Slow, boring, and the reason your deploy does not cause an outage.

3. DATA MIGRATIONS OVER LARGE TABLES GO IN BATCHES, not one UPDATE. A single
   statement over ten million rows takes a long lock and bloats the WAL.

4. CREATE INDEX CONCURRENTLY on a live table. A plain CREATE INDEX locks out
   writes for the duration. (It cannot run inside a transaction, so the
   migration needs autocommit mode.)

5. ALWAYS REVIEW AUTOGENERATED MIGRATIONS. Autogenerate is a first draft. It
   routinely proposes dropping a table it cannot see and reordering things
   destructively.
"""

from __future__ import annotations

import asyncio
from logging.config import fileConfig

from alembic import context
from sqlalchemy import pool
from sqlalchemy.engine import Connection
from sqlalchemy.ext.asyncio import async_engine_from_config

from app.config import settings
from app.db import Base
from app import models  # noqa: F401  -- import for the side effect of registering
                       # every model on Base.metadata. Without this import,
                       # autogenerate sees an empty schema and cheerfully
                       # generates a migration that drops all your tables.

config = context.config
config.set_main_option("sqlalchemy.url", settings.database_url)

if config.config_file_name is not None:
    fileConfig(config.config_file_name)

target_metadata = Base.metadata


def run_migrations_offline() -> None:
    """Emit SQL to stdout instead of executing it — for DBA review."""
    context.configure(url=settings.sync_database_url, target_metadata=target_metadata,
                      literal_binds=True, dialect_opts={"paramstyle": "named"})
    with context.begin_transaction():
        context.run_migrations()


def do_run_migrations(connection: Connection) -> None:
    context.configure(
        connection=connection,
        target_metadata=target_metadata,
        compare_type=True,          # detect column type changes
        compare_server_default=True,
    )
    with context.begin_transaction():
        context.run_migrations()


async def run_async_migrations() -> None:
    connectable = async_engine_from_config(
        config.get_section(config.config_ini_section, {}),
        prefix="sqlalchemy.", poolclass=pool.NullPool,
    )
    async with connectable.connect() as connection:
        await connection.run_sync(do_run_migrations)
    await connectable.dispose()


if context.is_offline_mode():
    run_migrations_offline()
else:
    asyncio.run(run_async_migrations())
